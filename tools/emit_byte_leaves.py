#!/usr/bin/env python3
"""Shape-agnostic byte-tier emitter: one naked function per transcribable leaf, body = the
original's bytes, with one generated comment line per instruction from the same decode the §1h
guard already runs.

THIS IS THE ASK, NOT THE DECISION. It refuses until docs/decisions.md carries a 1j authorising
`.byte` bodies: decision 1 authorised *single-instruction* asm with a uniform byte assertion and a
monotonic count, and `.byte` can encode several instructions while removing the assembler (the
third instrument) from the loop. Absence refuses.

    python3 -P tools/emit_byte_leaves.py --dry-run    # census only, writes nothing
    python3 -P tools/emit_byte_leaves.py             # writes game/leaf/bytes_family.cpp
"""
import collections
import csv
import sys

import capstone

import blocks as B
import leaf_family_census as C
import record_bytes_family as R

FAMILY = 'leaf_bytes'
BODY = 'game/leaf/bytes_family.cpp'
DECISION = 'docs/decisions.md'


def authorised(text: str) -> bool:
    """True only for a heading line the ratifier wrote: `### 1j.` at line start, no PROPOSED.

    Deliberately NOT a substring search. The first version was `'### 1j.' in open(DECISION).read()`
    and it authorised the tool the moment I wrote the 1j *proposal* -- because the proposal's prose
    quotes the very string the guard looked for ("which looks for `### 1j.`"). The refusal was
    defeated by the text that described it; a line-anchored match cannot be.
    """
    for line in text.splitlines():
        if line.startswith('### 1j.') and 'PROPOSED' not in line:
            return True
    return False


def transcribable():
    md = open(C.ELF, 'rb').read()
    cs = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    cs.detail = False
    landed = {int(r['address'], 16) for r in csv.DictReader(open('symbols/functions.csv'))}
    out, refused, members = [], collections.Counter(), []
    # The population is the CATALOGUE's unlanded rows in the band, not the leaf-shape census: the
    # shape census recognises 5,888 of the 12,092 rows, so emitting from it would land 4,033 where
    # the pre-registration says 4,034 -- a near-match that is the "two instruments, one number"
    # trap rather than agreement. Byte transcription is shape-agnostic; the population is the
    # partition's, so the counter (census_band.py) and the emitter count the same rows.
    for r in csv.DictReader(open('symbols/ghidra_functions.csv')):
        addr, size = int(r['address'], 16), int(r['size'])
        if not (1 <= size <= 16) or addr in landed:
            continue
        c = B.census(md, addr, size)
        if c['decoded'] != c['size'] or c['unplaced']:
            refused['decode'] += 1
            continue
        if c['blocks'] != 1 or c['calls']:
            refused['control flow'] += 1
            continue
        off = addr - C.FILE_BIAS
        members.append({'function': f'{FAMILY}_{addr:08x}', 'address': f'0x{addr:x}',
                        'size': str(size)})
        out.append({'address': addr, 'size': size,
                    'ins': list(cs.disasm(md[off:off + size], addr)),
                    'bytes': md[off:off + size]})
    # decisions.md 1j (iv)/(v), per row, through record_bytes_family.refusal -- ONE tooth set for
    # the counter, the gate and this emitter. The first version applied 1h alone and would have
    # emitted bodies for the 6,694 position-dependent and 65 trapping rows the census refuses: the
    # 647 retraction class at ten times the scale, in the one artifact nobody re-reads.
    kept = []
    for i, m in enumerate(out):
        reason, _ = R.refusal(members[i])
        if reason:
            refused[reason] += 1
            continue
        kept.append(m)
    return kept, refused


def main(argv):
    dry = '--dry-run' in argv
    ms, refused = transcribable()
    total = sum(m['size'] for m in ms)
    print(f'{FAMILY}: {len(ms)} transcribable leaves, {total} B; refused '
          f'{sum(refused.values())} ({dict(refused)})')
    if dry:
        print('dry run: nothing written')
        return 0
    try:
        ratifies = authorised(open(DECISION).read())
    except OSError:
        ratifies = False
    if not ratifies:
        raise SystemExit('refused: docs/decisions.md has no 1j authorising `.byte` bodies. '
                         'Decision 1 authorised one-instruction asm; this is a wider ask.')
    lines = ['// generated by tools/emit_byte_leaves.py -- do not edit',
             '// BYTE TRANSCRIPTION, not reconstruction: each body is the original extent copied',
             '// through .byte, with the decode in a comment generated from the same bytes.',
             '']
    for m in ms:
        key = f'{FAMILY}_{m["address"]:08x}'
        dis = ' ; '.join(f'{i.mnemonic} {i.op_str}'.strip() for i in m['ins'])
        lines.append(f'// {key} ({m["size"]} B): {dis}')
        lines.append(f'extern "C" __attribute__((naked)) void bb_{key}(void) {{')
        lines.append('  __asm__ volatile(".byte ' +
                     ', '.join(f'0x{b:02x}' for b in m['bytes']) + '");')
        lines.append('}')
        lines.append('')
    with open(BODY, 'w') as f:
        f.write('\n'.join(lines))
    print(f'body: {BODY}, {len(ms)} symbols')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
