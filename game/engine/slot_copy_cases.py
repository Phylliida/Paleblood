"""Cases for the slot copiers in game/engine/slot_copy.cpp.

Generated by tools/slot_copy_gen.py from the same decode of the image that writes the C++ file, so
the argument register each member reads from and the argument register each member writes to cannot
disagree between the two.

usage: slot_copy_cases.py OUT_DIR

One JSON per case into OUT_DIR/0x<address>/, the layout tools/preflight.py expects.

What these cases pin, and what they deliberately do not
------------------------------------------------------

The source holds an affine pattern, byte i = (start + step * i) & 0xff, so every byte is a different
value and a move at the wrong offset cannot match by coincidence. The destination is pre-filled with
one value, with a different value again before and after the region the body may write, so a store at
the wrong offset lands on a byte the original leaves alone and is reported as a write.

The two overlap cases are the load-bearing ones for this family. Some members read every source slot
before writing any (staged) and the rest load and store one slot at a time (interleaved). With the
destination sixteen bytes above the source an interleaved body stores over the slot it has not loaded
yet and copies its own output forward, while a staged body reads the original bytes throughout. The
reverse direction is the mirror situation, and which of the two discriminates for a given member
depends on which argument register holds its source.

Deliberately NOT pinned:

* The value left in xmm0-xmm3 at return. It is caller-saved and no caller of a void function reads
  it, so pinning it would pin the compiler's register allocation rather than the function.
* The order of stores that cannot alias each other. A member's destination slots never overlap one
  another, so for a staged member every load is already in a register before the first store, and no
  permutation of those stores changes a byte of the result. The C++ keeps the original's instruction
  order because that is what the bytes say, not because a case can see it.
"""

import json
import pathlib
import sys

# (address, source argument register, destination argument register, move count)
MEMBERS = [
    (0x00485C20, 'rdi', 'rsi', 4),
    (0x00499610, 'rsi', 'rdi', 4),
    (0x004BB970, 'rsi', 'rdi', 4),
    (0x004BE730, 'rsi', 'rdi', 4),
    (0x0063E8C0, 'rdx', 'rdi', 4),
    (0x0085C8B0, 'rdi', 'rsi', 8),
    (0x0085C8E0, 'rsi', 'rdi', 8),
    (0x009E1B10, 'rdi', 'rsi', 6),
    (0x009EE2C0, 'rdi', 'rsi', 6),
    (0x00BE2DA0, 'rdi', 'rsi', 8),
    (0x00C07DB0, 'rdi', 'rsi', 8),
    (0x00CBEB60, 'rdi', 'rsi', 4),
    (0x00DD73C0, 'rdi', 'rsi', 4),
    (0x00DD73E0, 'rsi', 'rdi', 4),
    (0x00DDCBE0, 'rdi', 'rsi', 4),
    (0x00DDCC00, 'rsi', 'rdi', 4),
    (0x00F31070, 'rsi', 'rdi', 6),
    (0x012C4950, 'rsi', 'rdi', 8),
    (0x014C79C0, 'rdi', 'rsi', 8),
    (0x01945EA0, 'rsi', 'rdi', 6),
    (0x01E19DB0, 'rsi', 'rdi', 6),
    (0x02113C30, 'rdi', 'rsi', 8),
    (0x026837E0, 'rsi', 'rdi', 4),
    (0x028CD340, 'rdi', 'rsi', 8),
    (0x028CD370, 'rsi', 'rdi', 8),
    (0x02BDFCA0, 'rsi', 'rdi', 8),
    (0x02C1B760, 'rsi', 'rdi', 4),
    (0x02C1CD10, 'rsi', 'rdi', 4),
    (0x02F01ED0, 'rdx', 'rdi', 4),
]

SOURCE_SIZE = 0x80
GUARD_SIZE = 0x10
JUNK_PREFIX = 0x30
DEST_SPAN = 0x80
DEST_SIZE = JUNK_PREFIX + DEST_SPAN + 0x40
PRE_FILL = 0xC7
SENTINEL = 0xE9

# byte i = (start + step * i) & 0xff, one distinct value per byte, so a move at the wrong offset
# cannot match by coincidence and no two regions of a case share a value.
AFFINE = [
    ('distinct_slots', (0x08, 5)),
    ('every_slot_wrong_byte', (0x30, 7)),
    ('last_slot_moved_only', (0x58, 11)),
    ('zero_source', None),
    ('read_past_last_slot', (0x60, 11)),
]
OVERLAP = (0x60, 11)
OVERLAP_OFFSET = 0x40
OVERLAP_SHIFT = 0x10


def pattern(count, spec):
    if spec is None:
        return bytes(count)
    start, step = spec
    return bytes((start + step * i) & 0xFF for i in range(count))


def doc(address, case_id, args, buffers, note):
    return {
        "schema": 1,
        "address": f"0x{address:08x}",
        "id": case_id,
        "args": args,
        "buffers": buffers,
        "memory": [{"addr": f"buf:{name}", "bytes": buf["bytes"]}
                   for name, buf in sorted(buffers.items())],
        "returns": "void",
        "note": note,
    }


def build(address, source_register, dest_register, moves):
    cases = []
    for case_id, spec in AFFINE:
        source = pattern(SOURCE_SIZE, spec)
        destination = bytes([PRE_FILL] * DEST_SIZE)
        note = (
            f"{case_id}: source and destination are separate, {moves} move(s). The destination is "
            f"pre-filled with 0x{PRE_FILL:02x} so a slot the body fails to store is visible, and the "
            f"{JUNK_PREFIX:#x} bytes before it and the 0x40 after it hold a different value again, "
            f"so a store at the wrong offset lands on a byte the original leaves alone. The source "
            f"holds a distinct value in every byte, so a load at the wrong offset reads a byte that "
            f"differs from the one it should have copied."
        )
        cases.append((case_id, doc(
            address, case_id,
            {source_register: "buf:source", dest_register: "buf:dest"},
            {"source": {"size": SOURCE_SIZE, "bytes": source.hex()},
             "guard": {"size": GUARD_SIZE, "bytes": bytes([SENTINEL] * GUARD_SIZE).hex()},
             "dest": {"size": DEST_SIZE, "bytes": destination.hex()}},
            note)))

    # The destination sits OVERLAP_SHIFT past the source in one case and before it in the other; the
    # region must reach past the WIDEST destination extent, not merely the span. Members do not all store
    # from their destination's start: 0x00dd73e0 loads from source+0x10/+0x20 and stores at
    # destination+0x60/+0x70, so its last 16-byte store ends 0x80 past the destination pointer. This
    # line was repaired in the generated artifact once and NOT here, so re-running the generator
    # reintroduced the defect -- a generator that cannot re-emit a repair is a repair with an expiry.
    region = pattern(OVERLAP_OFFSET + OVERLAP_SHIFT + DEST_SPAN, OVERLAP)
    buffers = {"region": {"size": len(region), "bytes": region.hex()}}
    for case_id, destination_offset in (
            ("overlap_dest_above_source", OVERLAP_OFFSET + OVERLAP_SHIFT),
            ("overlap_dest_below_source", OVERLAP_OFFSET - OVERLAP_SHIFT)):
        above = destination_offset > OVERLAP_OFFSET
        note = (
            f"{case_id}: source and destination overlap by {OVERLAP_SHIFT:#x} bytes with the "
            f"destination {'above' if above else 'below'} the source. An interleaved body stores "
            f"over the slot it has not loaded yet and copies its own output forward, while a staged "
            f"body has already read every slot. The two directions are separate cases because only "
            f"one of them discriminates for a given member, depending on which argument register "
            f"holds its source."
        )
        cases.append((case_id, doc(
            address, case_id,
            {source_register: f"buf:region+0x{OVERLAP_OFFSET:x}",
             dest_register: f"buf:region+0x{destination_offset:x}"},
            buffers, note)))
    return cases


def main(argv):
    if len(argv) != 2:
        print("usage: slot_copy_cases.py OUT_DIR", file=sys.stderr)
        return 2
    out = pathlib.Path(argv[1])
    total = 0
    for address, source_register, dest_register, moves in MEMBERS:
        here = out / f"0x{address:08x}"
        here.mkdir(parents=True, exist_ok=True)
        built = build(address, source_register, dest_register, moves)
        for case_id, entry in built:
            (here / f"{case_id}.json").write_text(
                json.dumps(entry, indent=2, sort_keys=True) + "\n")
            total += 1
        print(f"0x{address:08x}: {len(built)} case(s) -> {here}")
    print(f"{total} case(s) for {len(MEMBERS)} member(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
