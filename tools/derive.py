"""One number, one home.

This campaign has withdrawn 116,475, 13,307, 37,629, 6,749, 139 and 71.3%, and every withdrawal had the
same shape: the number lived in a sentence AND in code, only the code was re-run, and the sentence kept
asserting the old digits. A number that appears twice will diverge; a number that appears once cannot.

So: symbols/derived.json is the single store, generated by this tool from the tools that own each figure,
each value carrying the file and commit that produced it. Prose and comments READ a key; they do not
restate digits. `--check` regenerates in memory and refuses on any difference, which is what a test runs.

Keys not yet present are listed in PENDING and are explicitly PROVISIONAL: they come from loaders still
reading the CSV with their own DictReader rather than through tools/catalogue.py, and they enter this
file only after that migration and one re-derivation pass.

This module derives no figure. Every value is returned by the tool that owns it: `build()` calls the
loader's `compute()`, and it never re-implements a size filter, a disjointness test or an owner count.
Eight keys computed twice would be a second home born silently -- equal today only because two
implementations happen to agree, which is exactly the failure `catalogue.read_rows` and `rosters.compare`
were written to kill.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "symbols" / "derived.json"
sys.path.insert(0, str(ROOT / "tools"))
import rosters  # noqa: E402

# A refactor must not move a number it did not touch. Any key NOT under these prefixes has provenance
# independent of the five loaders being migrated, so it must be byte-identical across that commit; a
# frozen key that moves is a far stronger signal than the six provisional ones that are expected to.
MUTABLE_PREFIX = ("branch.", "band.", "frontier.", "thunk.")

PENDING = ()   # emptied when the five loaders moved to catalogue.read_rows; see the eight keys in build()


def head() -> str:
    try:
        return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True).stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def _chdir(path):
    import contextlib
    import os

    @contextlib.contextmanager
    def cm():
        old = os.getcwd()
        os.chdir(path)
        try:
            yield
        finally:
            os.chdir(old)
    return cm()


def build() -> dict:
    import progress as P
    import check_catalogue as K
    d = P.compute(str(ROOT))
    hits = K.scan()
    values = {
        "catalogue.functions": d["total"]["functions"],
        "catalogue.bytes": d["total"]["bytes"],
        "catalogue.maximal_extents": d["maximal"]["extents"],
        "catalogue.maximal_contained": d["maximal"]["contained"],
        "landed.tracked": d["tracked"]["functions"],
        "landed.edge_verified": d["edge_verified"]["functions"],
        "landed.verified": d["verified"]["functions"],
        "ledger.rows": (d["ledger"] or {}).get("rows"),
        "ledger.functions": (d["ledger"] or {}).get("functions"),
        "parses.sites": sum(r for _f, (_p, r) in hits.items()),
        "parses.files": len(hits),
        "inputs.ghidra_functions_sha256": d["inputs"]["ghidra_functions_sha256"],
        "inputs.functions_sha256": d["inputs"]["functions_sha256"],
    }
    # NOT derived here: one call per owner, and no filtering logic in this file.
    import branch_census as BC
    import leaf_frontier as LF
    import thunk_census as TC
    # CONTRACT: those three resolve their inputs relative to the working directory (`symbols/...`), unlike
    # progress/check_catalogue which anchor at ROOT. The bare-invocation test runs from /tmp on purpose and
    # caught exactly this: the new call path had lost the anchor the old one had. Owed: path constants.
    with _chdir(ROOT):
        f, lf, th = BC.compute(), LF.compute(), TC.compute()
    values.update({
        "branch.functions": f["branch"],
        "branch.landed": f["branch_landed"],
        "band.unlanded_independent": lf["independent"],
        "band.nested": lf["nested"],
        "frontier.addressable": lf["addressable"],
        "frontier.short": lf["short"],
        "thunk.rows": th["rows"],
        "thunk.branch_free": th["branch_free"],
    })
    return {
        "schema": 1,
        "generated_by": "tools/derive.py",
        "head": head(),
        "pending_provisional": list(PENDING),
        "values": dict(sorted(values.items())),
    }


def _load_json(path, what):
    path = Path(path)
    if not path.exists():
        print(f"derive: {what} {path} is missing -- a pre-registration that can evaporate is a sentence; refusing")
        return None
    try:
        return json.loads(path.read_text())
    except (json.JSONDecodeError, AttributeError) as exc:
        print(f"derive: {what} {path} is unreadable ({exc}) -- refusing rather than comparing nothing")
        return None


def compare(old_path, payload, prereg_path=None) -> int:
    """Refuse any move the pre-registration did not predict. `derive.py --compare before.json [--prereg p.json]`."""
    before = _load_json(old_path, "baseline")
    if before is None:
        return 3
    old = before.get("values", {})
    if not old:
        print(f"derive: baseline {old_path} holds no values -- refusing")   # this printed and then COMPARED
        return 3
    predicted = {}
    if prereg_path:
        doc = _load_json(prereg_path, "pre-registration")
        if doc is None:
            return 3
        predicted = doc.get("predicted", {})
        if not predicted:
            print(f"derive: pre-registration {prereg_path} holds no predictions -- refusing")
            return 3
    new = payload["values"]
    bad, lines = [], []
    for k in sorted(set(old) | set(new)):
        o, n = old.get(k), new.get(k)
        did_move = o != n
        pred = predicted.get(k, {}).get("prediction")
        if pred is None:
            # no prediction for this key: the prefix rule stands (mutable may move, everything else may not)
            if not did_move:
                continue
            tag = "mutable" if k.startswith(MUTABLE_PREFIX) else "FROZEN"
            if tag == "FROZEN":
                bad.append(k)
        elif pred == "identical":
            if not did_move:
                continue
            tag = "FROZEN"                      # predicted identical and moved -> the refactor altered a number
            bad.append(k)
        elif pred in ("up", "down"):
            if k not in old or k not in new:
                # appeared or vanished: a direction cannot be tested against None, and "moved" must not
                # be reported for a key that is simply absent from one side
                tag = "FROZEN/" + ("NEW" if k not in old else "GONE")
                bad.append(k)
            elif not did_move:
                tag = "MISSED"                  # predicted to move and did not: the migration missed a call site
                bad.append(k)
            elif (n > o) == (pred == "up"):
                tag = "mutable"
            else:
                tag = "AGAINST"                 # moved the other way: the parse was never that field
                bad.append(k)
        else:
            print(f"derive: pre-registration for {k} says {pred!r} -- refusing an unknown prediction")
            return 3
        if k not in old and not tag.endswith("/NEW"):
            tag += "/NEW"
        elif k not in new and not tag.endswith("/GONE"):
            tag += "/GONE"
        lines.append(f"derive: moved [{tag}] {k}: {o!r} -> {n!r}")
    for line in lines:
        print(line)
    if prereg_path:
        hit = sum(1 for k in predicted if k in old and k in new and old[k] == new[k])
        print(f"derive: pre-registration checked: {len(predicted)} key(s), {hit} with a before and after value")
    if bad:
        print(f"derive: {len(bad)} key(s) moved against the pre-registration -- {', '.join(bad)}")
        return 1
    print(f"derive: compare ok ({len(lines)} key(s) moved, none against the pre-registration)")
    return 0


def main(argv) -> int:
    if "--help" in argv:      # before build(): usage must not cost three capstone censuses
        print("derive.py [--check [--store P]] [--compare BEFORE [--prereg P]] [--payload P]")
        print("  no flags: write symbols/derived.json.  --check: stored == derived.  "
              "--compare: every move against a baseline, refused unless predicted.")
        return 0
    # --payload injects the current side: the comparison logic is what seven tests exercise, and it does
    # not care what the numbers are. Without it, every test pays three capstone censuses (290 s measured).
    if "--payload" in argv:
        inj = Path(argv[argv.index("--payload") + 1])
        if not inj.exists():
            print(f"derive: injected payload {inj} is missing -- refusing")
            return 3
        payload = json.loads(inj.read_text())
    else:
        payload = build()
    if "--compare" in argv:
        prereg = argv[argv.index("--prereg") + 1] if "--prereg" in argv else None
        return compare(argv[argv.index("--compare") + 1], payload, prereg)
    store = Path(argv[argv.index("--store") + 1]) if "--store" in argv else OUT
    if "--check" in argv:
        if not store.exists():
            print(f"derive: {store} is missing -- run tools/derive.py")
            return 3
        old = json.loads(store.read_text())
        unlisted, stale = rosters.compare(old.get("pending_provisional", []),
                                          payload.get("pending_provisional", []))
        if unlisted or stale:
            for k in unlisted:
                print(f"derive: PENDING entry {k!r} is not pending in this derivation")
            for k in stale:
                print(f"derive: PENDING entry {k!r} is stale -- prune it")
            return 1
        if old.get("values") != payload["values"]:
            keys = sorted(set(old.get("values", {})) | set(payload["values"]))
            for k in keys:
                a, b = old.get("values", {}).get(k), payload["values"].get(k)
                if a != b:
                    print(f"derive: {k}: stored {a!r} != derived {b!r}")
            return 1
        print(f"derive: ok ({len(payload['values'])} keys, head {payload.get('head', 'unknown')})")
        return 0
    OUT.write_text(json.dumps(payload, indent=1, sort_keys=False) + "\n")
    print(f"derive: wrote {OUT.relative_to(ROOT)} ({len(payload['values'])} keys, head {payload['head']})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
