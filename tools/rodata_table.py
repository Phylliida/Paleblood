#!/usr/bin/env python3
"""Lift a guest rodata table into a C++ constexpr array, with its extent derived and its bytes hashed.

Why this exists: the first hand-translated pilot reads two 16-bit tables in guest rodata
(0x02fc5120, 0x02fc4a40) through a two-level lookup -- level 1 indexed by the high byte,
level 2 by (high nibble + the level-1 value), then bit-tested with the low nibble.  A wrong nibble
in a hand-copied table is invisible in review and visible only in a differential, so the table is
generated from the binary and carries the sha256 of the exact span it was generated from.

Extent is *derived*, never guessed: 256 level-1 words, and the table ends 16 words past the largest
level-1 value that names a level-2 block.  A table whose extent was guessed is a table with a hole.

    python3 -P tools/rodata_table.py --elf ../data/bb/elf/eboot.elf --address 0x02fc5120 --name sg1
"""
import argparse
import hashlib
import struct
import sys
import time

import simd_census  # noqa: F401  (proves PYTHONPATH=tools: the campaign's other census tool)


def derive(blob, guest, level1_words=256):
    off = guest - 0x3FC000
    l1 = struct.unpack_from("<%dH" % level1_words, blob, off)
    bases = [v for v in l1 if v >= 2]
    if not bases:
        raise ValueError("no level-2 blocks named by level 1; extent cannot be derived")
    end = max(bases) + 16
    span = (end) * 2
    words = struct.unpack_from("<%dH" % end, blob, off)
    return words, span, max(bases)


def emit(path, name, guest, words, span, digest, elf):
    lines = [
        "// Generated by tools/rodata_table.py -- do not edit by hand.",
        f"// guest {guest:#010x}  bytes {span}  words {len(words)}  sha256 {digest}",
        f"// source {elf}",
        f"// The sha256 covers exactly the {span} bytes this table was read from; a re-dump that",
        "// disagrees is a table that no longer matches the binary it claims to describe.",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace bb::data {",
        "",
        f"inline constexpr std::array<std::uint16_t, {len(words)}> k_{name} = {{",
    ]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:04x}" for w in words[i:i + 8]) + ",")
    lines += [
        "};",
        "",
        f'inline constexpr char k_{name}_sha256[] = "{digest}";',
        f"inline constexpr std::uint32_t k_{name}_bytes = {span}u;",
        "",
        "}  // namespace bb::data",
        "",
    ]
    text = "\n".join(lines)
    with open(path, "w", newline="\n") as fh:
        fh.write(text)
    return text


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--elf", required=True)
    ap.add_argument("--address", required=True, help="guest address of the level-1 table")
    ap.add_argument("--name", required=True, help="C++ identifier suffix")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    t0 = time.monotonic()
    with open(args.elf, "rb") as fh:
        blob = fh.read()
    guest = int(args.address, 16)
    words, span, maxbase = derive(blob, guest)
    digest = hashlib.sha256(blob[guest - 0x3FC000:guest - 0x3FC000 + span]).hexdigest()
    text = emit(args.out, args.name, guest, words, span, digest, args.elf)
    # Two routes, sharing no object with the emit: re-read the bytes, re-derive the words, and
    # compare against what was written to disk by parsing the file back.
    back = [int(t, 16) for t in
            text.split("= {", 1)[1].split("};", 1)[0].replace(",", " ").split()]
    if tuple(back) != words:
        print("FAIL: emitted words do not round-trip against the bytes", file=sys.stderr)
        return 1
    dt = time.monotonic() - t0
    print(f"{args.name}: guest {guest:#x} words {len(words)} span {span} B "
          f"max level-2 base {maxbase} sha256 {digest[:16]} T_data {dt:.3f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
