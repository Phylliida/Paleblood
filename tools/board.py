#!/usr/bin/env python3
"""Print the board's numbers, each read from an artifact and each naming its source.

The burndown was the one long-lived artifact still written by hand, and it carried two numbers that
no test could contradict (a tier reported as waiting while landed; a band reported as the frontier's
remaining work while 96.7% disjoint from it). This tool is the shape that makes a summary sentence
falsifiable: every line is computed from a file in symbols/ and names that file, and
test/test_board.py regenerates the committed copy and diffs it.

A line this tool cannot source is printed as `not sourced` WITH THE QUESTION, never omitted and never
guessed -- absence refuses, and a number whose definition cannot be named is not a number yet.
"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import catalogue  # noqa: E402  -- typed reader: address/size are ints, one radix law
import progress  # noqa: E402  -- the hook's own clause; the board QUOTES it and never recomputes

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SYM = os.path.join(ROOT, 'symbols')
SYM = DEFAULT_SYM
OUT = os.path.join(ROOT, 'docs', 'board.md')
LANDED = ('edge-verified', 'verified')


def rows(name):
    """Every row through catalogue.read_rows -- the one reader the gate allows outside catalogue.py."""
    return list(catalogue.read_rows(os.path.join(SYM, name)))


def count(name):
    """Data rows of a table WITHOUT an address column (verification/reviews/quarantine).

    Counted as lines minus the header, and printed as `rows` rather than as `functions`: the two are
    equal here only because these tables hold one row per function, which the committed number shows.
    """
    with open(os.path.join(SYM, name)) as fh:
        return len(fh.read().splitlines()) - 1


def addrs(name, key='address'):
    return {r[key] for r in rows(name)}


def _render():
    fn = rows('functions.csv')
    by = collections.Counter(r['status'] for r in fn)
    bodied = [r for r in fn if r['status'] in LANDED]
    reach = len(rows('ghidra_functions.csv'))
    fr = [r for r in rows('leaf_frontier.csv') if r['class'] == 'addressable']
    fr_all = rows('leaf_frontier.csv')
    bodied_addr = {r['address'] for r in fn if r['status'] in LANDED}
    transcribed_addr = {r['address'] for r in fn if r['status'] not in LANDED}
    ret = addrs('retired.csv')
    n_ver = count('verification.csv')
    n_quar = count('quarantine.csv')
    n_rev = count('reviews.csv')
    gh = [(r['address'], r['size']) for r in rows('ghidra_functions.csv')]
    inband = [(a, s) for a, s in gh if 1 <= s <= 16]
    inband_unlanded = [(a, s) for a, s in inband if a not in bodied_addr]
    fr_addrs = {r['address'] for r in fr}
    given = sorted(fr_addrs & ret)
    dup = sorted(fr_addrs & bodied_addr)
    tr = sorted(fr_addrs & transcribed_addr)
    n = len(bodied)
    pct = lambda a, b: f'{100.0 * a / b:.2f}%' if b else 'n/a'
    lines = [
        '# board -- generated by `tools/board.py`; do not edit',
        '',
        f'rows **{n}** (`edge-verified` {by["edge-verified"]} + `verified` {by["verified"]})'
        f' | `original` (transcription only) {by["original"]} [symbols/functions.csv]',
        '',
        '**The reach clause below is quoted from `progress.reach_line`, the same function the pre-commit',
        'hook prints. It is not recomputed here: one fact printed twice is two that can drift, and',
        '`84.43%` PROGRESS (`branch-free`) and `87.11%` (`all rows`) are two different denominators**',
        'that a hand-written burndown confused once already.',
        '',
        '    ' + progress.reach_line(ROOT),
        '',
        f'`verified` **{by["verified"]}** [symbols/functions.csv]',
        f'approvals **{n_rev}** [symbols/reviews.csv, rows]'
        f' | differential records **{n_ver}** [symbols/verification.csv, rows]'
        f' | quarantined **{n_quar}** [symbols/quarantine.csv, rows]',
        f'verification surplus **{n_ver - n}** = {n_ver} verification rows - {n} bodied rows'
        f' (computed here, so it cannot go stale as a carry)',
        f'frontier **{len(fr)} addressable | {sum(1 for r in fr_all if r["class"] != "addressable")} short'
        f' | {len(fr_all)} total** [symbols/leaf_frontier.csv]',
        f'frontier n bodied **{len(dup)}** (must be 0 -- a frontier row that has a body is not a candidate)',
        f'frontier n transcription-only **{len(tr)}**'
        + (f' -- {", ".join(hex(a) for a in tr)}' if tr else ''),
        f'frontier n retired **{len(given)}**'
        + (f' -- OPEN DEFECT {", ".join(hex(a) for a in given)}: retired, yet advertised as a candidate'
           if given else ' -- clean'),
        f'retired **{len(ret)}** [symbols/retired.csv]',
        f'in-band (1..16 B) **{len(inband)}** | landed bodies **{len(inband) - len(inband_unlanded)}**'
        f' | unlanded **{len(inband_unlanded)}** [symbols/ghidra_functions.csv x symbols/functions.csv]',
        '',
        '## not sourced -- printed, never guessed',
        '',
        '- **zero_init approvals (carried as 0 of 528)**: no artifact in `symbols/` names this population.',
        '  The question: which file decides a row is `zero_init`, and which decides it is approved?',
        '- **the census equation (`206 + 6004 + 0 = 6210`)**: emitted by `tools/leaf_shape_census.py`,',
        '  which decodes the image; kept out of this tool so the board stays file-only and cheap.',
        '- **the position band (`7956 address dependent + 65 trap = 8021`)**: emitted by',
        '  `tools/record_bytes_family.py` refusal over the band, which needs the same decode.',
        '',
    ]
    return '\n'.join(lines)


def render(root=None):
    """Render against ROOT, or against a synthetic tree so the defect branches can be exercised.

    A branch that has stopped firing and a branch that cannot fire look identical from outside, so the
    OPEN DEFECT line gets a planted control against a directory that advertises a retired address.
    The override is restored in `finally`: a synthetic render must not leak into the next one.
    """
    global SYM
    old, SYM = SYM, (os.path.join(root, 'symbols') if root else DEFAULT_SYM)
    try:
        return _render()
    finally:
        SYM = old


def main(argv):
    text = render()
    if '--write' in argv:
        with open(OUT, 'w') as fh:
            fh.write(text)
        print(f'wrote {os.path.relpath(OUT, ROOT)} ({len(text.splitlines())} lines)')
        return 0
    print(text, end='')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(os.sys.argv[1:]))
