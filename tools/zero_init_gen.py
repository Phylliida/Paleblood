"""Emit game/engine/zero_init.cpp and game/engine/zero_init_cases.py from the image.

This family zeroes the low 0x78 bytes of the object its second argument points at, stores its first
argument at +0x78, and returns a constant zero. Both files come from one decode of the image, so the
offsets the implementation writes and the offsets the cases expect cannot disagree, and every member
is checked against the first member's bytes before it is emitted, because the whole premise of
treating them as one family is that they are the same code at different addresses.

The members are taken from symbols/functions.csv rather than listed here: tools/ is inside
check_agnostic.py's scope, which forbids game addresses outside game/ and symbols/.

usage: zero_init_gen.py [--check] [--limit N]
"""
import csv
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from function_qualification import _decode_with_objdump  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMAGE = os.environ.get('BB_IMAGE', '')
FUNCTIONS = os.path.join(ROOT, 'symbols', 'functions.csv')
CODE_BIAS = 0x3FC000

SYSTEM = 'engine'
PREFIX = 'engine_zero_init_'

ARG_REGS = ('rdi', 'rsi', 'rdx', 'rcx', 'r8', 'r9')
OBJECT = re.compile(r'^qword ptr \[([a-z0-9]+)(?:\+0x([0-9a-f]+))?\]$')
REGISTER = re.compile(r'^r[a-z0-9]+$')


class Bad(Exception):
    pass


def addresses():
    found = []
    with open(FUNCTIONS, newline='') as handle:
        for row in csv.DictReader(handle):
            if row['system'] == SYSTEM and row['name'].startswith(PREFIX):
                found.append(int(row['address'], 16))
    if not found:
        raise Bad(f'{FUNCTIONS}: no {SYSTEM} rows named {PREFIX}*')
    return sorted(found)


def decode_member(image, va, size):
    """(zero offsets, pointer register, pointer offset, returns constant) for one member.

    The body has to be exactly: a run of eight-byte zero stores into one base register, one store of
    an argument register into that same base, and a constant zero return. Anything else is not this
    family and is refused rather than approximated.
    """
    raw = image[va - CODE_BIAS: va - CODE_BIAS + size]
    if len(raw) != size:
        raise Bad(f'0x{va:08x}: only {len(raw)} of {size} bytes are in the image')
    zeroes, pointer, base = [], None, None
    for ins in _decode_with_objdump(raw, va):
        mnemonic, operands = ins['mnemonic'], ins['operands']
        if not mnemonic:  # the byte objdump printed on its own line: see family_scan.py
            continue
        if mnemonic == 'ret':
            break
        if mnemonic == 'mov':
            left, _, right = operands.partition(',')
            match = OBJECT.match(left.strip())
            if not match:
                raise Bad(f'0x{va:08x}: store to {left.strip()}')
            here, offset = match.group(1), int(match.group(2) or '0', 16)
            if base is None:
                base = here
            if here != base:
                raise Bad(f'0x{va:08x}: store through {here}, not {base}')
            if right.strip() == '0x0':
                zeroes.append(offset)
            elif REGISTER.match(right.strip()):
                if pointer is not None:
                    raise Bad(f'0x{va:08x}: a second register store')
                pointer = (right.strip(), offset)
            else:
                raise Bad(f'0x{va:08x}: store of {right.strip()}')
        elif mnemonic == 'xor' and operands.replace(' ', '') in ('eax,eax', 'rax,rax'):
            continue
        else:
            raise Bad(f'0x{va:08x}: unexpected {mnemonic} {operands}')
    if base is None or not zeroes or pointer is None:
        raise Bad(f'0x{va:08x}: {len(zeroes)} zero store(s), pointer store {pointer}')
    if base not in ARG_REGS or pointer[0] not in ARG_REGS:
        raise Bad(f'0x{va:08x}: base {base}, pointer register {pointer[0]}')
    if len(set(zeroes)) != len(zeroes):
        raise Bad(f'0x{va:08x}: a zero offset is stored twice')
    return sorted(zeroes), pointer[0], pointer[1], base


def sizes():
    """Extent per address, from the catalogue Ghidra exported alongside the registry."""
    table = {}
    path = os.path.join(ROOT, 'symbols', 'ghidra_functions.csv')
    with open(path, newline='') as handle:
        for row in csv.reader(handle):
            if len(row) >= 2 and row[0].startswith('0x'):
                table[int(row[0], 16)] = int(row[1])
    return table


CPP_HEAD = '''// SPDX-License-Identifier: GPL-2.0-or-later
//
// Generated by tools/zero_init_gen.py from the bytes in the image. Each body performs the original's
// stores in the original's order. Do not edit by hand: re-run the generator, which writes this file
// and the case file from the same decode.
//
// Every member of this family has the same body at a different address, so the wrapper differs only
// in its address and its exported name.

#include <cstddef>
#include <cstdint>

namespace {

// What the original leaves in eax. Every member ends `xor eax, eax; ret`, so the wrapper returns
// zero rather than nothing; a void wrapper would leave the caller's rax untouched.
constexpr std::uint64_t kReturnsZero = 0;

// The object every member zeroes before storing its first argument at the end. The fields are named
// for their offsets because nothing is known about what the object means yet; rename one when a
// caller shows what it holds.
struct zero_init_object {
__FIELDS__};

__ASSERTS__}  // namespace

'''

CPP_BODY = '''
// 0x{address:08x}: zeroes at {zeroes}, stores the first argument at +0x{pointer:02x}.
// Returns the constant the original leaves in eax; the cases enter with a nonzero rax, so a body
// that fell off the end instead of returning would be visible as a register difference.
extern "C" std::uint64_t {name}(void *rdi_argument, void *rsi_argument) {{
    auto *object = static_cast<zero_init_object *>(rsi_argument);
{stores}    object->stored_argument = rdi_argument;
    return kReturnsZero;
}}

'''


def render_cpp(members):
    zeroes = members[0]['zeroes']
    pointer = members[0]['pointer']
    total = pointer + 8
    entries = sorted([(offset, 'zero') for offset in zeroes] + [(pointer, 'pointer')])
    fields, asserts = [], []
    cursor = 0
    for offset, kind in entries:
        if offset < cursor:
            raise Bad(f'a field at +0x{offset:02x} overlaps the one before it')
        if offset > cursor:
            fields.append(f'    std::uint8_t unknown_padding_0x{cursor:04x}[0x{offset - cursor:x}];')
        if kind == 'zero':
            name = f'unknown_0x{offset:04x}'
            fields.append(f'    std::uint64_t {name};  // zeroed')
        else:
            name = 'stored_argument'
            fields.append(f'    void *{name};  // +0x{offset:02x}')
        asserts.append(f'static_assert(offsetof(zero_init_object, {name}) == 0x{offset:04x});')
        cursor = offset + 8
    if cursor < total:
        fields.append(f'    std::uint8_t unknown_padding_0x{cursor:04x}[0x{total - cursor:x}];')
    asserts.append(f'static_assert(sizeof(zero_init_object) == 0x{total:02x});')
    head = CPP_HEAD.replace('__FIELDS__', ''.join(f'{field}\n' for field in fields))
    head = head.replace('__ASSERTS__', ''.join(f'{assertion}\n' for assertion in asserts))
    lines = [head]
    for member in members:
        zero_text = ', '.join(f'0x{offset:02x}' for offset in member['zeroes'])
        stores = ''.join(f'    object->unknown_0x{offset:04x} = 0;\n'
                         for offset in member['zeroes'])
        lines.append(CPP_BODY.format(address=member['address'], name=member['name'],
                                     zeroes=zero_text, pointer=member['pointer'], stores=stores))
    return ''.join(lines)


CASES_HEAD = '''#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0-or-later
"""Cases for the zero-initialisers in game/engine/zero_init.cpp.

Generated by tools/zero_init_gen.py from the same decode of the image that writes the C++ file.

usage: zero_init_cases.py OUT_DIR

One JSON per case into OUT_DIR/0x<address>/, the layout tools/preflight.py expects.

What these cases pin, and what they deliberately do not
------------------------------------------------------

The object is pre-filled with 0xff, so a field the body fails to zero is a byte that differs from
the original's output, and the region before the object and the 0x20 bytes after it hold a different
value again, so a store at the wrong offset lands on a byte the original leaves alone. The value
stored at +0x78 is the address of a third buffer, which is what makes it checkable: a wrong register
or a wrong offset produces a different value, not merely a suspicious one.

The pointer case is the one that matters most. Every other case would still pass if the body zeroed
the object and stored the wrong bytes at +0x78, because 0xff pre-fill and a zeroed field are the
only things the other cases compare.

Deliberately NOT pinned:

* The order of the zero stores. They write to disjoint eight-byte spans, so no permutation of them
  changes a byte of the result.
* The value left in eax. The original returns a constant zero rather than anything computed, and the
  cases pin it twice over: they enter with a nonzero rax and compare the return, so a wrapper that
  returns nothing shows up as 0xdeadbeef where the original gives 0.
"""

import json
import pathlib
import sys

# (address, exported symbol, zero offsets, pointer offset)
MEMBERS = [
'''


CASES_TAIL = ''']

OBJECT_SIZE = 0x80
GUARD_BEFORE = 0x20
GUARD_AFTER = 0x20
PAYLOAD_SIZE = 0x20
PREFIX = 0x5A
PRE_FILL = 0xFF
PAYLOAD_FILL = 0xA5


# The value every case enters with. The original clears eax, so a wrapper that returns nothing
# leaves this behind and differs on the `returns` comparison; a quiet entry rax would let that
# mistake pass, which is exactly how the family passed before the harness could set rax at all.
ENTRY_RAX = "0xdeadbeef"


def doc(address, case_id, args, buffers, note, returns="i32"):
    return {
        "schema": 1,
        "address": f"0x{address:08x}",
        "id": case_id,
        "args": dict(args, rax=ENTRY_RAX),
        "buffers": buffers,
        "memory": [{"addr": f"buf:{name}", "bytes": buf["bytes"]}
                   for name, buf in sorted(buffers.items())],
        "returns": returns,
        "note": note,
    }


def build(address, zeroes, pointer):
    cases = []
    holes = OBJECT_SIZE - len(zeroes) * 8 - 8
    common = (
        f"The object is pre-filled with 0x{PRE_FILL:02x}, so any of the {len(zeroes)} zeroed "
        f"eight-byte fields that the body skips stays 0x{PRE_FILL:02x} and differs from the "
        f"original. The {GUARD_BEFORE:#x} bytes before it and the {GUARD_AFTER:#x} after it hold "
        f"0x{PREFIX:02x}, so a store outside the object is a write on memory the original leaves "
        f"alone. {holes} byte(s) of the object are neither zeroed nor written by the original and "
        f"must stay 0x{PRE_FILL:02x}."
    )

    def object_case(case_id, note, returns="i32", payload=False):
        buffers = {
            "object": {"size": GUARD_BEFORE + OBJECT_SIZE + GUARD_AFTER,
                       "bytes": (bytes([PREFIX] * GUARD_BEFORE)
                                 + bytes([PRE_FILL] * OBJECT_SIZE)
                                 + bytes([PREFIX] * GUARD_AFTER)).hex()},
            "payload": {"size": PAYLOAD_SIZE, "bytes": bytes([PAYLOAD_FILL] * PAYLOAD_SIZE).hex()},
        }
        args = {"rdi": "buf:payload", "rsi": f"buf:object+0x{GUARD_BEFORE:x}"}
        return doc(address, case_id, args, buffers, note, returns)

    cases.append(('every_field_zeroed', object_case(
        'every_field_zeroed',
        f"all_fields: every one of the {len(zeroes)} zeroed fields, with the object pre-filled to "
        f"differ from zero. {common}")))

    cases.append(('pointer_value', object_case(
        'pointer_value',
        f"pointer_value: the pointer at +0x{pointer:#x} must be the address of the payload buffer, "
        f"whose bytes are 0x{PAYLOAD_FILL:02x}. A body that stored a different register, or the "
        f"pointer at the wrong offset, produces a different value here. {common}")))

    cases.append(('object_untouched_beyond', object_case(
        'object_untouched_beyond',
        f"guard: the same body with the object's guards holding a distinct value, to show the stores "
        f"stay inside the {OBJECT_SIZE:#x}-byte object. {common}")))

    # A null pointer argument: the original stores it like any other value, so this separates a body
    # that stores the register from one that dereferences it.
    buffers = {
        "object": {"size": GUARD_BEFORE + OBJECT_SIZE + GUARD_AFTER,
                   "bytes": (bytes([PREFIX] * GUARD_BEFORE)
                             + bytes([PRE_FILL] * OBJECT_SIZE)
                             + bytes([PREFIX] * GUARD_AFTER)).hex()},
    }
    cases.append(('null_pointer_stored', doc(
        address, 'null_pointer_stored',
        {"rdi": "0x0", "rsi": f"buf:object+0x{GUARD_BEFORE:x}"},
        buffers,
        f"null_pointer_stored: the first argument is null, which the original stores at "
        f"+0x{pointer:#x} without reading it. A body that dereferenced the argument would fault "
        f"here. {common}")))
    return cases


def main(argv):
    if len(argv) != 2:
        print("usage: zero_init_cases.py OUT_DIR", file=sys.stderr)
        return 2
    out = pathlib.Path(argv[1])
    total = 0
    for address, name, zeroes, pointer in MEMBERS:
        here = out / f"0x{address:08x}"
        here.mkdir(parents=True, exist_ok=True)
        built = build(address, zeroes, pointer)
        for case_id, entry in built:
            (here / f"{case_id}.json").write_text(
                json.dumps(entry, indent=2, sort_keys=True) + "\\n")
            total += 1
        print(f"0x{address:08x}: {len(built)} case(s) -> {here}")
    print(f"{total} case(s) for {len(MEMBERS)} member(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
'''


def main(argv):
    if not IMAGE:
        raise Bad('set BB_IMAGE to the executable the registry was derived from')
    with open(IMAGE, 'rb') as handle:
        image = handle.read()
    table = sizes()
    limit = None
    if '--limit' in argv:
        limit = int(argv[argv.index('--limit') + 1])

    selected = addresses()
    if limit is not None:
        selected = selected[:limit]

    members, reference = [], None
    for address in selected:
        if address not in table:
            raise Bad(f'0x{address:08x}: not in ghidra_functions.csv')
        size = table[address]
        zeroes, pointer_register, pointer_offset, base = decode_member(image, address, size)
        body = image[address - CODE_BIAS: address - CODE_BIAS + size]
        if reference is None:
            reference = (address, body, zeroes, pointer_register, pointer_offset, base)
        else:
            first, first_body, first_zeroes, first_register, first_offset, first_base = reference
            if body != first_body:
                raise Bad(f'0x{address:08x}: bytes differ from 0x{first:08x}')
            if (zeroes, pointer_register, pointer_offset, base) != (
                    first_zeroes, first_register, first_offset, first_base):
                raise Bad(f'0x{address:08x}: shape differs from 0x{first:08x}')
        name = f'bb_{SYSTEM}_zero_init_{address:08x}'
        members.append({'address': address, 'name': name, 'zeroes': zeroes,
                        'pointer': pointer_offset, 'size': size})
        print(f'0x{address:08x} {size:3} bytes, {len(zeroes)} zero stores, '
              f'{pointer_register} -> +0x{pointer_offset:02x}, base {base}')

    rows = ''.join(
        f'    (0x{member["address"]:08X}, {member["name"]!r}, '
        f'({", ".join(str(o) for o in member["zeroes"])}), 0x{member["pointer"]:02x}),\n'
        for member in members)
    outputs = {'zero_init.cpp': render_cpp(members),
               'zero_init_cases.py': CASES_HEAD + rows + CASES_TAIL}
    root = os.path.join(ROOT, 'game', 'engine')
    stale = 0
    for name in sorted(outputs):
        path = os.path.join(root, name)
        current = None
        if os.path.exists(path):
            with open(path) as handle:
                current = handle.read()
        if current == outputs[name]:
            print(f'{name} unchanged')
            continue
        stale = 1
        if '--check' in argv:
            print(f'{name}: stale')
            continue
        with open(path, 'w') as handle:
            handle.write(outputs[name])
        print(f'wrote {path}')
    if '--check' not in argv:
        os.chmod(os.path.join(root, 'zero_init_cases.py'), 0o755)
    return stale


if __name__ == '__main__':
    try:
        sys.exit(main(sys.argv[1:]))
    except Bad as problem:
        print(f'{os.path.basename(__file__)}: {problem}', file=sys.stderr)
        sys.exit(1)
