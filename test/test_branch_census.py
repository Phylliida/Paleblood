"""symbols/branch_band.csv.gz is the denominator's provenance: regenerate it and diff the text.

Both of progress.py's denominators are only as good as this table, and the table's first version was
wrong by a radix (sizes parsed as hex when ghidra_functions.csv's size column is decimal, so every
window overshot into the neighbour and inherited its branches). A number whose artifact is not
regenerated by a test is a number nobody will notice going stale.
"""
import gzip
import os
import pathlib
import subprocess
import sys
import tempfile
import unittest

REPO = pathlib.Path(__file__).resolve().parents[1]


class BranchCensusTest(unittest.TestCase):
    def test_committed_branch_band_reproduces(self):
        with tempfile.TemporaryDirectory() as td:
            out = os.path.join(td, "band.csv.gz")
            env = dict(os.environ, PYTHONPATH=str(REPO / "tools"))
            r = subprocess.run([sys.executable, "-P", str(REPO / "tools" / "branch_census.py"),
                                "--out", out],
                               cwd=str(REPO), env=env, capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stderr[-3000:])
            self.assertIn("undecoded 0", r.stdout, "a row that fails to decode is silently excluded "
                          "from both denominators -- fix the decode, not the count")
            got = gzip.open(out, "rt").read()
            want = gzip.open(REPO / "symbols" / "branch_band.csv.gz", "rt").read()
            self.assertEqual(want, got, "symbols/branch_band.csv.gz is stale: regenerate with "
                             "tools/branch_census.py --out symbols/branch_band.csv.gz")


if __name__ == "__main__":
    unittest.main()
