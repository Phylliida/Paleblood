"""Emit game/engine/slot_copy.cpp and game/engine/slot_copy_cases.py from the image.

Both files come from one decode of the image, so the offsets, the argument register each member
reads from and the argument register each member writes to cannot disagree between the
implementation and the cases. That matters for this family: the members are near-identical copies
whose sources and destinations sit in different argument registers, and reading a hand-written table
of directions got several of them backwards.

usage: slot_copy_gen.py [--check]
"""
import csv
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from function_qualification import _decode_with_objdump  # noqa: E402

IMAGE = '/home/bepis/modding/decomp/data/bb/elf/eboot.elf'
FUNCTIONS = '/home/bepis/modding/decomp/Paleblood/symbols/functions.csv'
CODE_BIAS = 0x3FC000

SYSTEM = 'engine'
PREFIX = 'engine_slot_copy_'


def addresses():
    """The members of this family, taken from the registry rather than listed here.

    tools/ is in check_agnostic.py's SCOPE, which forbids game-specific addresses and names outside
    game/ and symbols/, so the family has to be discovered from symbols/functions.csv.
    """
    found = []
    with open(FUNCTIONS, newline='') as handle:
        for row in csv.DictReader(handle):
            if row['system'] == SYSTEM and row['name'].startswith(PREFIX):
                found.append(int(row['address'], 16))
    if not found:
        raise Bad(f'{FUNCTIONS}: no {SYSTEM} rows named {PREFIX}*')
    return sorted(found)

ARG_REGS = ('rdi', 'rsi', 'rdx', 'rcx', 'r8', 'r9')
MEMORY = re.compile(r'^(xmmword|qword|dword|word|byte) ptr \[([a-z0-9]+)(?:\+0x([0-9a-f]+))?\]$')
WIDTHS = {'xmmword': 16, 'qword': 8, 'dword': 4, 'word': 2, 'byte': 1}


class Bad(Exception):
    pass


def decode_member(image, va):
    """The (op, width, base, offset, register) sequence of one member.

    Intel syntax puts the destination operand first, so an operand in memory on the left of the comma
    is a store and one on the right is a load. The width qualifier sits on the memory operand.
    """
    raw = image[va - CODE_BIAS: va - CODE_BIAS + 0x100]
    sequence = []
    for ins in _decode_with_objdump(raw, va):
        if ins['mnemonic'] == 'ret':
            break
        if not ins['mnemonic'].startswith('vmov'):
            raise Bad(f'0x{va:08x}: not a move: {ins["mnemonic"]} {ins["operands"]}')
        operands = [o.strip() for o in ins['operands'].split(',')]
        if len(operands) != 2:
            raise Bad(f'0x{va:08x}: {ins["operands"]}')
        left, right = operands
        m_left, m_right = MEMORY.match(left), MEMORY.match(right)
        if m_left and not m_right:
            op, match, register = 'store', m_left, right
        elif m_right and not m_left:
            op, match, register = 'load', m_right, left
        else:
            raise Bad(f'0x{va:08x}: neither or both operands in memory: {ins["operands"]}')
        base, offset = match.group(2), int(match.group(3) or '0', 16)
        if base not in ARG_REGS:
            raise Bad(f'0x{va:08x}: base register {base} is not an argument register')
        sequence.append((op, WIDTHS[match.group(1)], base, offset, register))
    if not sequence:
        raise Bad(f'0x{va:08x}: no moves')
    return sequence


def summarise(va, sequence):
    """(source register, destination register, load offsets, store offsets, staged)."""
    loads = [(w, b, o) for op, w, b, o, _ in sequence if op == 'load']
    stores = [(w, b, o) for op, w, b, o, _ in sequence if op == 'store']
    if not loads or not stores:
        raise Bad(f'0x{va:08x}: {len(loads)} load(s), {len(stores)} store(s)')
    if len({b for _, b, _ in loads}) != 1 or len({b for _, b, _ in stores}) != 1:
        raise Bad(f'0x{va:08x}: more than one base register on a side')
    if len({w for w, _, _ in loads}) != 1 or len({w for w, _, _ in stores}) != 1:
        raise Bad(f'0x{va:08x}: mixed widths')
    source, destination = loads[0][1], stores[0][1]
    if source == destination:
        raise Bad(f'0x{va:08x}: source and destination are both {source}')
    kinds = [op for op, _, _, _, _ in sequence]
    staged = kinds.index('store') > max(i for i, k in enumerate(kinds) if k == 'load')
    return (source, destination, [o for _, _, o in loads], [o for _, _, o in stores], staged)


CPP_HEAD = '''// SPDX-License-Identifier: GPL-2.0-or-later
//
// Generated by tools/slot_copy_gen.py from the bytes in the image. Each body is one move per
// instruction of the original, in the original's order, so the load-before-store staging of a member
// and the order of its stores are both preserved. Do not edit by hand: re-run the generator, which
// writes this file and the case file from the same decode.
//
// A member's source and destination are not always rdi and rsi. The comment above each wrapper names
// the argument register each side uses, and the offsets are byte offsets from that argument.

#include <cstdint>
#include <immintrin.h>

namespace {

inline const void *at(const void *base, std::uintptr_t offset) {
    return static_cast<const std::uint8_t *>(base) + offset;
}

inline void *at(void *base, std::uintptr_t offset) {
    return static_cast<std::uint8_t *>(base) + offset;
}

'''


def render_cpp(members):
    lines = [CPP_HEAD]
    # Name every byte offset the family uses. The offsets are the family's whole content, so they
    # get one constant each rather than a literal at every use site.
    offsets = sorted({offset for member in members for _, _, _, offset, _ in member['sequence']})
    for offset in offsets:
        lines.append(f'constexpr std::uintptr_t kOffset{offset:02x} = 0x{offset:02x};')
    lines.append('')
    for index, member in enumerate(members):
        # The helper takes the source first and the destination second so its body reads in copy
        # order. The argument register each side actually occupies is a property of the wrapper.
        lines.append(f'// 0x{member["address"]:08x}: {member["count"]} move(s), '
                     f'{member["description"]}.')
        lines.append(f'inline void copy_{member["address"]:08x}_{index}('
                     f'const void *source, void *destination) {{')
        declared = set()
        for op, width, _, offset, register in member['sequence']:
            if op == 'load':
                intrinsic = '_mm_load_ps' if width == 16 else '_mm_load_ss'
                # A register the original reuses is assigned again rather than redeclared, so these are
                # not const.
                binding = '__m128 ' if register not in declared else ''
                declared.add(register)
                lines.append(f'    {binding}{register} = {intrinsic}('
                             f'reinterpret_cast<const float *>(at(source, kOffset{offset:02x})));')
            else:
                intrinsic = '_mm_store_ps' if width == 16 else '_mm_store_ss'
                lines.append(f'    {intrinsic}(reinterpret_cast<float *>(at('
                             f'destination, kOffset{offset:02x})), {register});')
        lines.append('}')
        lines.append('')
    lines.append('}  // namespace')
    lines.append('')
    for index, member in enumerate(members):
        # validate_functions.py derives the expected hook as 'bb_' + the registry name, so the
        # exported symbol has to match symbols/functions.csv exactly, layout tag included.
        layout = 'staged' if member['staged'] else 'interleaved'
        name = f'bb_engine_slot_copy_{layout}_{member["address"]:08x}'
        source, destination = member['source'], member['destination']
        # The caller passes its arguments in ARG_REGS order, so a wrapper that only names its first
        # two parameters cannot reach a member whose source sits in rdx or beyond: those arguments
        # stay in their registers and are never handed to the C function. Name one parameter per
        # register the member actually uses, in ARG_REGS order, and let the call site pick them out
        # by register.
        # A C parameter list is positional, so a member that skips rsi still needs a slot for it:
        # without one its rdx value would be handed to the function in rsi instead.
        used = [r for r in ARG_REGS[:max(ARG_REGS.index(source), ARG_REGS.index(destination)) + 1]]
        parameters = ', '.join(f'void *{r}_argument' for r in used)
        arguments = ', '.join(f'{r}_argument' for r in (source, destination))
        lines.append(f'// 0x{member["address"]:08x}: source in {source}, '
                     f'destination in {destination}, '
                     f'{"staged" if member["staged"] else "interleaved"}.')
        lines.append(f'extern "C" void {name}({parameters}) {{')
        # The skipped registers are named but not read, which is the point: they hold the caller's
        # values for the registers they do name, and the ones in between exist only to keep the
        # positions right.
        for register in used:
            if register not in (source, destination):
                lines.append(f'    (void){register}_argument;')
        lines.append(f'    copy_{member["address"]:08x}_{index}({arguments});')
        lines.append('}')
        lines.append('')
    return '\n'.join(lines)


CASES_HEAD = '''#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0-or-later
"""Cases for the slot copiers in game/engine/slot_copy.cpp.

Generated by tools/slot_copy_gen.py from the same decode of the image that writes the C++ file, so
the argument register each member reads from and the argument register each member writes to cannot
disagree between the two.

usage: slot_copy_cases.py OUT_DIR

One JSON per case into OUT_DIR/0x<address>/, the layout tools/preflight.py expects.

What these cases pin, and what they deliberately do not
------------------------------------------------------

The source holds an affine pattern, byte i = (start + step * i) & 0xff, so every byte is a different
value and a move at the wrong offset cannot match by coincidence. The destination is pre-filled with
one value, with a different value again before and after the region the body may write, so a store at
the wrong offset lands on a byte the original leaves alone and is reported as a write.

The two overlap cases are the load-bearing ones for this family. Some members read every source slot
before writing any (staged) and the rest load and store one slot at a time (interleaved). With the
destination sixteen bytes above the source an interleaved body stores over the slot it has not loaded
yet and copies its own output forward, while a staged body reads the original bytes throughout. The
reverse direction is the mirror situation, and which of the two discriminates for a given member
depends on which argument register holds its source.

Deliberately NOT pinned:

* The value left in xmm0-xmm3 at return. It is caller-saved and no caller of a void function reads
  it, so pinning it would pin the compiler's register allocation rather than the function.
* The order of stores that cannot alias each other. A member's destination slots never overlap one
  another, so for a staged member every load is already in a register before the first store, and no
  permutation of those stores changes a byte of the result. The C++ keeps the original's instruction
  order because that is what the bytes say, not because a case can see it.
"""

import json
import pathlib
import sys

# (address, source argument register, destination argument register, move count)
MEMBERS = [
'''

CASES_TAIL = ''']

SOURCE_SIZE = 0x80
GUARD_SIZE = 0x10
JUNK_PREFIX = 0x30
DEST_SPAN = 0x80
DEST_SIZE = JUNK_PREFIX + DEST_SPAN + 0x40
PRE_FILL = 0xC7
SENTINEL = 0xE9

# byte i = (start + step * i) & 0xff, one distinct value per byte, so a move at the wrong offset
# cannot match by coincidence and no two regions of a case share a value.
AFFINE = [
    ('distinct_slots', (0x08, 5)),
    ('every_slot_wrong_byte', (0x30, 7)),
    ('last_slot_moved_only', (0x58, 11)),
    ('zero_source', None),
    ('read_past_last_slot', (0x60, 11)),
]
OVERLAP = (0x60, 11)
OVERLAP_OFFSET = 0x40
OVERLAP_SHIFT = 0x10


def pattern(count, spec):
    if spec is None:
        return bytes(count)
    start, step = spec
    return bytes((start + step * i) & 0xFF for i in range(count))


def doc(address, case_id, args, buffers, note):
    return {
        "schema": 1,
        "address": f"0x{address:08x}",
        "id": case_id,
        "args": args,
        "buffers": buffers,
        "memory": [{"addr": f"buf:{name}", "bytes": buf["bytes"]}
                   for name, buf in sorted(buffers.items())],
        "returns": "void",
        "note": note,
    }


def build(address, source_register, dest_register, moves):
    cases = []
    for case_id, spec in AFFINE:
        source = pattern(SOURCE_SIZE, spec)
        destination = bytes([PRE_FILL] * DEST_SIZE)
        note = (
            f"{case_id}: source and destination are separate, {moves} move(s). The destination is "
            f"pre-filled with 0x{PRE_FILL:02x} so a slot the body fails to store is visible, and the "
            f"{JUNK_PREFIX:#x} bytes before it and the 0x40 after it hold a different value again, "
            f"so a store at the wrong offset lands on a byte the original leaves alone. The source "
            f"holds a distinct value in every byte, so a load at the wrong offset reads a byte that "
            f"differs from the one it should have copied."
        )
        cases.append((case_id, doc(
            address, case_id,
            {source_register: "buf:source", dest_register: "buf:dest"},
            {"source": {"size": SOURCE_SIZE, "bytes": source.hex()},
             "guard": {"size": GUARD_SIZE, "bytes": bytes([SENTINEL] * GUARD_SIZE).hex()},
             "dest": {"size": DEST_SIZE, "bytes": destination.hex()}},
            note)))

    # The destination sits OVERLAP_SHIFT past the source in one case and before it in the other; the
    # region must reach past the WIDEST destination extent, not merely the span. Members do not all store
    # from their destination's start: 0x00dd73e0 loads from source+0x10/+0x20 and stores at
    # destination+0x60/+0x70, so its last 16-byte store ends 0x80 past the destination pointer. This
    # line was repaired in the generated artifact once and NOT here, so re-running the generator
    # reintroduced the defect -- a generator that cannot re-emit a repair is a repair with an expiry.
    region = pattern(OVERLAP_OFFSET + OVERLAP_SHIFT + DEST_SPAN, OVERLAP)
    buffers = {"region": {"size": len(region), "bytes": region.hex()}}
    for case_id, destination_offset in (
            ("overlap_dest_above_source", OVERLAP_OFFSET + OVERLAP_SHIFT),
            ("overlap_dest_below_source", OVERLAP_OFFSET - OVERLAP_SHIFT)):
        above = destination_offset > OVERLAP_OFFSET
        note = (
            f"{case_id}: source and destination overlap by {OVERLAP_SHIFT:#x} bytes with the "
            f"destination {'above' if above else 'below'} the source. An interleaved body stores "
            f"over the slot it has not loaded yet and copies its own output forward, while a staged "
            f"body has already read every slot. The two directions are separate cases because only "
            f"one of them discriminates for a given member, depending on which argument register "
            f"holds its source."
        )
        cases.append((case_id, doc(
            address, case_id,
            {source_register: f"buf:region+0x{OVERLAP_OFFSET:x}",
             dest_register: f"buf:region+0x{destination_offset:x}"},
            buffers, note)))
    return cases


def main(argv):
    if len(argv) != 2:
        print("usage: slot_copy_cases.py OUT_DIR", file=sys.stderr)
        return 2
    out = pathlib.Path(argv[1])
    total = 0
    for address, source_register, dest_register, moves in MEMBERS:
        here = out / f"0x{address:08x}"
        here.mkdir(parents=True, exist_ok=True)
        built = build(address, source_register, dest_register, moves)
        for case_id, entry in built:
            (here / f"{case_id}.json").write_text(
                json.dumps(entry, indent=2, sort_keys=True) + "\\n")
            total += 1
        print(f"0x{address:08x}: {len(built)} case(s) -> {here}")
    print(f"{total} case(s) for {len(MEMBERS)} member(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
'''


def main(argv):
    with open(IMAGE, 'rb') as handle:
        image = handle.read()
    members = []
    for address in addresses():
        sequence = decode_member(image, address)
        source, destination, loads, stores, staged = summarise(address, sequence)
        description = ('loads at ' + ' '.join(f'0x{o:02x}' for o in loads)
                       + ', stores at ' + ' '.join(f'0x{o:02x}' for o in stores))
        members.append({'address': address, 'source': source, 'destination': destination,
                        'loads': loads, 'stores': stores, 'staged': staged,
                        'sequence': sequence, 'count': len(sequence),
                        'description': description})
        print(f'0x{address:08x} {source}->{destination} {len(sequence)} moves '
              f'{"staged" if staged else "interleaved"} {description}')

    rows = ''.join(
        f'    (0x{member["address"]:08X}, {member["source"]!r}, {member["destination"]!r}, '
        f'{member["count"]}),\n' for member in members)
    outputs = {'slot_copy.cpp': render_cpp(members),
               'slot_copy_cases.py': CASES_HEAD + rows + CASES_TAIL}
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'game', 'engine')
    stale = 0
    for name in sorted(outputs):
        path = os.path.join(root, name)
        current = None
        if os.path.exists(path):
            with open(path) as handle:
                current = handle.read()
        if current == outputs[name]:
            print(f'{name} unchanged')
            continue
        stale = 1
        if '--check' in argv:
            print(f'{name}: stale')
            continue
        with open(path, 'w') as handle:
            handle.write(outputs[name])
        print(f'wrote {path}')
    if '--check' not in argv:
        os.chmod(os.path.join(root, 'slot_copy_cases.py'), 0o755)
        # A write that did what it was asked is rc 0. Returning the staleness count here made a correct
        # run indistinguishable from --check finding drift -- promote.py's defect, arriving again.
        return 0
    return stale


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
